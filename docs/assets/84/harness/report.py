"""Builds results/grades.md and the committed, row-free results/*.jsonl from a run.

usage: report.py <run results dir> <grades.json> <out dir>

grades.json lists only the answers that were not correct; every other
answer in a run file was graded correct. Rows are dropped on the way out:
they are the store's data, and this repository is public.
"""
import glob, json, math, os, statistics, sys

PRICE = {  # $ per MTok: input, cache read, output (list prices, 2026-11-01)
    "haiku": (0.10, 0.01, 0.50),
    "sonnet": (2.0, 0.20, 10.0),
    "opus": (4.0, 0.20, 20.0),
}
KEEP = ("id", "q", "interp", "sql", "checks", "usage", "gen_s", "error", "ran", "run_error", "rowCount", "columns")


def main(src, grades_path, out):
    grades = json.load(open(grades_path))
    os.makedirs(out, exist_ok=True)
    rows, details = [], []
    for f in sorted(glob.glob(os.path.join(src, "*.jsonl"))):
        tag = os.path.basename(f)[:-6]
        recs = [json.loads(l) for l in open(f)]
        if not recs:
            continue
        with open(os.path.join(out, tag + ".jsonl"), "w") as w:
            for r in recs:
                w.write(json.dumps({k: r.get(k) for k in KEEP}) + "\n")
        g = grades.get(tag, {})
        c = sum(1 for r in recs if r["id"] not in g)
        p = sum(1 for v in g.values() if v[0] == "P")
        x = sum(1 for v in g.values() if v[0] == "W")
        cost = ""
        model = next((m for m in PRICE if m in tag), None)
        if model:
            pin, pcache, pout = PRICE[model]
            usd = sum(r["usage"].get("in", 0) * pin + r["usage"].get("cache_read", 0) * pcache + r["usage"].get("out", 0) * pout for r in recs) / 1e6
            cost = f"{usd / len(recs):.4f}"
        gen = sorted(r["gen_s"] for r in recs)
        rows.append(f"| `{tag}` | {len(recs)} | {c} | {p} | {x} | {cost} | {statistics.median(gen):.1f} | {gen[math.ceil(0.9 * len(gen)) - 1]:.1f} |")
        for qid, (grade, why) in sorted(g.items()):
            details.append(f"| `{tag}` | {qid} | {grade} | {why} |")
    with open(os.path.join(out, "grades.md"), "w") as w:
        w.write("# NQ0 grades\n\nGenerated by `harness/report.py`. Scale and method: docs/84 §12.1. "
                "Every answer not listed under *Not correct* was graded correct.\n\n")
        w.write("| Run | Questions | Correct | Partial | Wrong | $ / question | Median s | p90 s |\n|---|---|---|---|---|---|---|---|\n")
        w.write("\n".join(rows) + "\n\n## Not correct\n\n| Run | Question | Grade | Why |\n|---|---|---|---|\n")
        w.write("\n".join(details) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
