#!/usr/bin/env node
// R79 MV0 — turns docs/assets/80/results/<browser>/*.json into the markdown
// tables RESULTS.md embeds (written to results/tables.md and stdout). Numbers
// are pooled across repetitions from the raw per-packet arrays, never
// transcribed by hand.
//
//   node docs/assets/80/harness/report.mjs [--results DIR]

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const i = process.argv.indexOf('--results');
const RES = resolve(i >= 0 ? process.argv[i + 1] : join(HERE, '..', 'results'));
const BROWSERS = ['chromium', 'firefox', 'webkit'].filter((b) => existsSync(join(RES, b)));
const SKIP = 5; // start-up packets per run

function q(xs, p) {
  const v = xs.filter(Number.isFinite).sort((a, b) => a - b);
  if (!v.length) return null;
  return v[Math.min(v.length - 1, Math.max(0, Math.ceil(p * v.length) - 1))];
}
const f = (x, d = 1) => (x === null || x === undefined ? '–' : Number(x).toFixed(d));
const mp = (xs, d = 1) => (xs.length ? `${f(q(xs, 0.5), d)} / ${f(q(xs, 0.95), d)}` : '–');

function load(browser) {
  const dir = join(RES, browser);
  const runs = [];
  let meta = null;
  let alignment = null;
  let aec = null;
  for (const name of readdirSync(dir).sort()) {
    const j = JSON.parse(readFileSync(join(dir, name), 'utf8'));
    if (name === 'meta.json') meta = j;
    else if (name === 'alignment.json') alignment = j;
    else if (name === 'aec-smoke.json') aec = j;
    else runs.push(j);
  }
  return { meta, alignment, aec, runs };
}

function key(o) {
  return `${o.capture}|${o.source}|${o.frameDurationUs}|${o.transport}|${o.application ?? 'default'}`;
}

function pool(runs) {
  const groups = new Map();
  for (const r of runs) {
    const k = key(r.opts);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(r);
  }
  const rows = [];
  for (const [k, rs] of groups) {
    const [capture, source, fd, transport, app] = k.split('|');
    const ok = rs.filter((r) => r.raw && !r.fatal && !(r.errors || []).length);
    const err = rs.map((r) => r.fatal ?? (r.errors || []).join('; ')).find((e) => e);
    const enc = [], dec = [], bytes = [], dur = new Map(), transit = [], depth = [], ig = [], arr = [], wait = [];
    let underruns = 0, packets = 0, supported = null, ctx = null, contiguousBlocks = null;
    for (const r of ok) {
      const sr = r.audioContext.sampleRate;
      ctx = r.audioContext;
      supported = r.support?.withFrameDuration?.supported ?? supported;
      for (const c of r.raw.chunks.slice(SKIP)) {
        enc.push(c[6]); bytes.push(c[2]);
        dur.set(c[3], (dur.get(c[3]) || 0) + 1);
        packets++;
      }
      for (const d of r.raw.decoded.slice(SKIP)) dec.push(d[3]);
      if (r.raw.transitsFrames) for (const t of r.raw.transitsFrames.slice(SKIP)) transit.push((t / sr) * 1000);
      if (r.output) { underruns += r.output.underruns; if (r.output.depthMs?.median !== undefined) depth.push(r.output.depthMs.median); }
      if (r.inGraphLatencyMs?.median !== undefined) ig.push(r.inGraphLatencyMs.median);
      const cap = r.workletCapture ?? r.mstp;
      if (cap?.arrivalIntervalMs?.median !== undefined) arr.push(cap.arrivalIntervalMs.p95);
      if (r.workletCapture) wait.push(r.workletCapture.quantumAlignmentWaitMs.median);
    }
    rows.push({ capture, source, fdMs: Number(fd) / 1000, transport, app, reps: rs.length, okReps: ok.length, err,
      supported, packets, dur: Object.fromEntries([...dur].map(([d, n]) => [d / 1000, n])), enc, dec, bytes,
      transit, depth, ig, arr, wait, underruns, ctx });
  }
  const order = ['mstp', 'worklet'];
  rows.sort((a, b) => order.indexOf(a.capture) - order.indexOf(b.capture) || a.source.localeCompare(b.source)
    || a.transport.localeCompare(b.transport) || a.app.localeCompare(b.app) || a.fdMs - b.fdMs);
  return rows;
}

function durStr(d) {
  const e = Object.entries(d);
  if (!e.length) return '–';
  const tot = e.reduce((a, [, n]) => a + n, 0);
  return e.map(([k, n]) => `${k} ms${e.length > 1 ? ` (${((100 * n) / tot).toFixed(0)}%)` : ''}`).join(', ');
}

const out = [];
const P = (s = '') => out.push(s);

P('<!-- generated by docs/assets/80/harness/report.mjs — do not edit by hand -->');
P();
P('### Per browser');
P();
P('| | ' + BROWSERS.map((b) => b).join(' | ') + ' |');
P('|---|' + BROWSERS.map(() => '---').join('|') + '|');
const data = Object.fromEntries(BROWSERS.map((b) => [b, load(b)]));
const rowsBy = Object.fromEntries(BROWSERS.map((b) => [b, pool(data[b].runs)]));
const pick = (b, pred) => rowsBy[b].filter(pred);
const line = (label, fn) => P(`| ${label} | ${BROWSERS.map((b) => fn(b)).join(' | ')} |`);
line('Engine build (Playwright, headless)', (b) => `${b === 'webkit' ? 'WebKit (WPE, **not Safari**)' : b === 'chromium' ? 'Chromium' : 'Firefox'} ${data[b].meta?.version ?? '?'}`);
line('`isConfigSupported` opus 48k mono 40k, frameDuration 10 ms', (b) => {
  const r = pick(b, (r) => r.fdMs === 10 && r.supported !== null)[0];
  return r ? (r.supported ? 'yes' : '**no**') : '–';
});
line('`isConfigSupported` frameDuration 20 ms', (b) => {
  const r = pick(b, (r) => r.fdMs === 20 && r.supported !== null)[0];
  return r ? (r.supported ? 'yes' : '**no**') : '–';
});
for (const fd of [10, 20]) {
  line(`Actual packet duration (Opus TOC), asked ${fd} ms`, (b) => {
    const d = {};
    for (const r of pick(b, (r) => r.fdMs === fd && r.app === 'default')) for (const [k, n] of Object.entries(r.dur)) d[k] = (d[k] || 0) + n;
    return durStr(d);
  });
}
for (const fd of [10, 20]) {
  const sel = (r) => r.fdMs === fd && r.app === 'default' && r.transport === 'inpage';
  line(`Encode latency ms, median / p95 (${fd} ms)`, (b) => mp(pick(b, sel).flatMap((r) => r.enc), 2));
  line(`Decode latency ms, median / p95 (${fd} ms)`, (b) => mp(pick(b, sel).flatMap((r) => r.dec), 2));
  line(`Packet bytes, median / p95 (${fd} ms, 40 kbit/s)`, (b) => mp(pick(b, sel).flatMap((r) => r.bytes), 0));
}
line('MediaStreamTrackProcessor on Window', (b) => (pick(b, (r) => r.capture === 'mstp' && r.okReps > 0).length ? 'yes' : 'no'));
line('Worklet capture → `AudioData` → `AudioEncoder` works', (b) => {
  const w = pick(b, (r) => r.capture === 'worklet' && r.transport === 'inpage');
  return w.length && w.every((r) => r.okReps === r.reps) ? `yes (${w.reduce((a, r) => a + r.packets, 0)} packets)` : 'no';
});
line('Worklet 10 ms block arrival interval p95 ms (main thread)', (b) => {
  const xs = pick(b, (r) => r.capture === 'worklet' && r.source === 'synth').flatMap((r) => r.arr);
  return xs.length ? f(q(xs, 0.5)) : '–';
});
line('Opus lookahead seen by the app (offline probe), samples / ms', (b) => {
  const a = data[b].alignment?.runs?.filter((r) => !r.application) ?? [];
  const v = a.map((r) => r.decodedMinusInputSamples).filter(Number.isFinite);
  return v.length ? `${q(v, 0.5)} / ${f((q(v, 0.5) / 48), 1)}` : '–';
});
line("…with `opus.application: 'lowdelay'`", (b) => {
  const a = data[b].alignment?.runs?.filter((r) => r.application === 'lowdelay') ?? [];
  const v = a.map((r) => r.decodedMinusInputSamples).filter(Number.isFinite);
  return v.length ? `${q(v, 0.5)} / ${f((q(v, 0.5) / 48), 1)}` : '–';
});
line("`opus.application` kept by `isConfigSupported` (`voip` / `lowdelay`)", (b) => {
  const r = data[b].runs.find((r) => r.support?.withFrameDurationVoip);
  if (!r) return '–';
  const g = (k) => (r.support[k]?.echoedOpus?.application ? 'kept' : 'dropped');
  return `${g('withFrameDurationVoip')} / ${g('withFrameDurationLowdelay')}`;
});
line('Fake mic track settings with EC/NS/AGC requested', (b) => {
  const r = data[b].runs.find((r) => r.opts?.source === 'gum' && r.track);
  if (!r) return '–';
  const t = r.track.settings;
  return `EC ${t.echoCancellation ?? '?'}, NS ${t.noiseSuppression ?? '?'}, AGC ${t.autoGainControl ?? '?'}, ${t.sampleRate ?? '?'} Hz`;
});
line('WebTransport (datagram loopback to relay `/echo`)', (b) => (pick(b, (r) => r.transport === 'wt' && r.okReps > 0).length ? 'yes' : 'no'));
line('AudioContext `baseLatency` / `outputLatency` s (null sink, not a device)', (b) => {
  const r = pick(b, (r) => r.ctx)[0];
  return r ? `${f(r.ctx.baseLatency, 4)} / ${f(r.ctx.outputLatencyAtEnd ?? r.ctx.outputLatency, 4)}` : '–';
});
P();
P('Latencies are wall-clock (`performance.now()`) on the main thread. Firefox runs with');
P('`privacy.reduceTimerPrecision=false`; WebKit clamps `performance.now()` to 1 ms, so its');
P('encode/decode numbers are quantised to 0 or 1 ms.');
P();

P('### Capture-node → playout-ready transit (worklet capture, synthetic source)');
P();
P('Per decoded packet: AudioContext frame at which it reached the output worklet minus the');
P('frame at which its first sample entered the capture worklet. This is the smallest fixed');
P('playout delay that would play that packet on time, before any network: it contains the');
P('packet duration, the Opus lookahead, the worklet→main→worklet hops, encode and decode.');
P('Device input and output latency are **not** in it (no real device headless).');
P();
P('| Browser | Frame | Opus application | Transport | median ms | p95 ms | p99 ms | max ms | packets |');
P('|---|---|---|---|---|---|---|---|---|');
for (const b of BROWSERS) {
  for (const r of pick(b, (r) => r.capture === 'worklet' && r.source === 'synth' && r.transit.length)) {
    P(`| ${b} | ${r.fdMs} ms | ${r.app} | ${r.transport} | ${f(q(r.transit, 0.5))} | ${f(q(r.transit, 0.95))} | ${f(q(r.transit, 0.99))} | ${f(Math.max(...r.transit))} | ${r.transit.length} |`);
  }
}
P();

P('### Every configuration');
P();
P('| Browser | Capture | Source | Frame | App | Transport | Runs ok | Packet dur | Enc ms p50/p95 | Dec ms p50/p95 | Bytes p50/p95 | Buffer depth p50 ms | Underruns | Onset in-graph p50 ms | Error |');
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const b of BROWSERS) {
  for (const r of rowsBy[b]) {
    P(`| ${b} | ${r.capture} | ${r.source} | ${r.fdMs} ms | ${r.app} | ${r.transport} | ${r.okReps}/${r.reps} | ${durStr(r.dur)} | ${mp(r.enc, 2)} | ${mp(r.dec, 2)} | ${mp(r.bytes, 0)} | ${r.depth.length ? f(q(r.depth, 0.5)) : '–'} | ${r.okReps ? r.underruns : '–'} | ${r.ig.length ? f(q(r.ig, 0.5)) : '–'} | ${r.err ? r.err.slice(0, 80) : ''} |`);
  }
}
P();
const md = out.join('\n') + '\n';
writeFileSync(join(RES, 'tables.md'), md);
// Splice into RESULTS.md between its markers, so the doc never drifts from
// the data.
const doc = join(RES, '..', 'RESULTS.md');
if (existsSync(doc)) {
  const text = readFileSync(doc, 'utf8');
  const re = /(<!-- BEGIN generated[^\n]*-->\n)[\s\S]*?(<!-- END generated -->)/;
  if (re.test(text)) writeFileSync(doc, text.replace(re, (_, a, b) => `${a}\n${md.replace(/^<!--[^\n]*-->\n\n/, '')}\n${b}`));
}
process.stdout.write(md);
