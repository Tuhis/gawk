package relayconsole

import (
	"encoding/json"
	"net/netip"
	"net/url"
	"strconv"
	"strings"
)

// QR tiers (docs/76 §7.1 "Join from this network").
const (
	// TierNamed: the PoP's own HTTPS page on its named host; no app needed.
	TierNamed = "named"
	// TierLinkedPinned: the home app; devices here switch by themselves.
	TierLinkedPinned = "linked-pinned"
	// TierStandalone: a gawk UI with ?relay=<LAN literal>&certHash=.
	TierStandalone = "standalone"
	// TierNone: there is no address a guest could use yet.
	TierNone = "none"
)

// JoinQR is the join link the console's QR code carries, and its tier.
//
//   - Named host known: https://<named>:<ui port>, the page and the relay on
//     one origin, a publicly trusted certificate (§6.11 item 39).
//   - Linked, pinned only: the home app's origin. The offer it sends a guest
//     here carries the pinned candidate (§6.12).
//   - Anything else — standalone, waiting, revoked, re-pair, and offline,
//     where home's page no longer loads at the venue: a gawk UI's landing
//     link naming the relay by its LAN literal and pinned hashes (§6.1 item
//     5), in the form gawk-app's own share links use.
func JoinQR(s State) (link string, tier string) {
	if s.NamedHost != "" {
		return "https://" + hostPort(s.NamedHost, s.UIPort), TierNamed
	}
	if s.Header == HeaderLinked && s.HomeOrigin != "" {
		return strings.TrimRight(s.HomeOrigin, "/"), TierLinkedPinned
	}
	relay := relayURL(s)
	if relay == "" {
		return "", TierNone
	}
	origin := strings.TrimRight(s.HomeOrigin, "/")
	if origin == "" {
		origin = DefaultAppOrigin
	}
	link = origin + "/#/?relay=" + url.QueryEscape(relay)
	if h := hashList(s); h != "" {
		link += "&certHash=" + h
	}
	return link, TierStandalone
}

// ServerLink is the native apps' form of the standalone link (§6.1 item 5,
// the R66 grammar's gawk://server), canonical as the link vectors spell it:
// relay, certHash, label, in that order, with %20 for a space. "" without a
// LAN address.
func ServerLink(s State) string {
	relay := relayURL(s)
	if relay == "" {
		return ""
	}
	link := "gawk://server?relay=" + url.QueryEscape(relay)
	if h := hashList(s); h != "" {
		link += "&certHash=" + h
	}
	if s.DisplayName != "" {
		link += "&label=" + strings.ReplaceAll(url.QueryEscape(s.DisplayName), "+", "%20")
	}
	return link
}

// ConfigJS is /app/config.js for the host's own machine (§6.1 item 6): the
// relay by LAN address (loopback when there is none) with its pinned
// hashes — devCertHashHex generalised — and requirePublishSecret false,
// because on a loopback origin the app's fallback would prompt for a
// secret (the docs/41 §4.2.2 trap).
func ConfigJS(s State) []byte {
	relay := relayURL(s)
	if relay == "" {
		relay = "https://" + netip.AddrPortFrom(netip.AddrFrom4([4]byte{127, 0, 0, 1}), uint16(port(s.RelayPort))).String()
	}
	hashes := []string{}
	for _, h := range s.Hashes {
		if h != "" {
			hashes = append(hashes, h)
		}
	}
	// Field order is the golden's; json.Marshal escapes <, > and &, so no
	// value can end the script early.
	b, _ := json.Marshal(struct {
		RelayURL             string   `json:"relayUrl"`
		RelayCertHashes      []string `json:"relayCertHashes"`
		RequirePublishSecret bool     `json:"requirePublishSecret"`
	}{relay, hashes, false})
	out := []byte("// Generated by gawk-relay for this machine's /app/ (docs/76 §6.1 item 6).\nwindow.__GAWK_CONFIG__ = ")
	out = append(out, b...)
	return append(out, ";\n"...)
}

// relayURL is https://<LAN literal>:<port>, "" without a LAN address.
func relayURL(s State) string {
	if !s.LanAddr.IsValid() {
		return ""
	}
	return "https://" + netip.AddrPortFrom(s.LanAddr.WithZone(""), uint16(port(s.RelayPort))).String()
}

// hashList is the certHash value: the non-empty hashes, comma-joined.
func hashList(s State) string {
	var hs []string
	for _, h := range s.Hashes {
		if h != "" {
			hs = append(hs, h)
		}
	}
	return strings.Join(hs, ",")
}

func port(p int) int {
	if p <= 0 || p > 65535 {
		return DefaultRelayPort
	}
	return p
}

func hostPort(host string, p int) string {
	return host + ":" + strconv.Itoa(port(p))
}
