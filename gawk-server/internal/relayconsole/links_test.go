package relayconsole

import (
	"net/netip"
	"strings"
	"testing"
)

var (
	h1 = strings.Repeat("a1", 32)
	h2 = strings.Repeat("b2", 32)
)

func lanState(header string) State {
	return State{
		Header:      header,
		DisplayName: "Assembly 2026",
		LanAddr:     netip.MustParseAddr("192.168.1.20"),
		Hashes:      [2]string{h1, h2},
	}
}

// docs/76 §7.1 "Join from this network": the QR payload per tier, pinned.
func TestJoinQRGoldens(t *testing.T) {
	named := lanState(HeaderLinked)
	named.HomeOrigin = "https://gawk.ioio.fi"
	named.NamedHost = "p-7k2m9x.pop.gawk.ioio.fi"

	linked := lanState(HeaderLinked)
	linked.HomeOrigin = "https://gawk.ioio.fi"

	ownHome := lanState(HeaderLinked)
	ownHome.HomeOrigin = "https://watch.example.org/"

	v6 := lanState(HeaderStandalone)
	v6.LanAddr = netip.MustParseAddr("fd12:3456::1")
	v6.Hashes = [2]string{h1, ""}

	port := lanState(HeaderStandalone)
	port.RelayPort = 5544

	offline := lanState(HeaderOffline)
	offline.HomeOrigin = "https://gawk.ioio.fi"

	noLAN := lanState(HeaderStandalone)
	noLAN.LanAddr = netip.Addr{}

	standalone := "https://gawk.ioio.fi/#/?relay=https%3A%2F%2F192.168.1.20%3A4433&certHash=" + h1 + "," + h2
	for _, c := range []struct {
		name      string
		s         State
		url, tier string
	}{
		{"named", named, "https://p-7k2m9x.pop.gawk.ioio.fi:4433", TierNamed},
		{"linked, pinned only", linked, "https://gawk.ioio.fi", TierLinkedPinned},
		{"linked to another fleet", ownHome, "https://watch.example.org", TierLinkedPinned},
		{"standalone", lanState(HeaderStandalone), standalone, TierStandalone},
		{"waiting to pair", lanState(HeaderWaiting), standalone, TierStandalone},
		{"revoked", lanState(HeaderRevoked), standalone, TierStandalone},
		{"repair", lanState(HeaderRepair), standalone, TierStandalone},
		// Offline: home's page does not load at the venue, so the pinned
		// link is the one that works for a guest who already has the app.
		{"offline", offline, "https://gawk.ioio.fi/#/?relay=https%3A%2F%2F192.168.1.20%3A4433&certHash=" + h1 + "," + h2, TierStandalone},
		{"standalone v6, one hash", v6, "https://gawk.ioio.fi/#/?relay=https%3A%2F%2F%5Bfd12%3A3456%3A%3A1%5D%3A4433&certHash=" + h1, TierStandalone},
		{"standalone, other port", port, "https://gawk.ioio.fi/#/?relay=https%3A%2F%2F192.168.1.20%3A5544&certHash=" + h1 + "," + h2, TierStandalone},
		{"no LAN address", noLAN, "", TierNone},
	} {
		url, tier := JoinQR(c.s)
		if url != c.url || tier != c.tier {
			t.Errorf("%s:\n got  %q (%s)\n want %q (%s)", c.name, url, tier, c.url, c.tier)
		}
	}
}

// The gawk://server form, restated from the R66 link vectors
// (gawk-broadcast-desktop/crates/engine/tests/link-vectors.json,
// "server/accept: a LAN relay with both hashes and a label" and the IPv6
// vector), byte for byte in their canonical form.
func TestServerLinkMatchesTheLinkVectors(t *testing.T) {
	s := lanState(HeaderStandalone)
	want := "gawk://server?relay=https%3A%2F%2F192.168.1.20%3A4433&certHash=" + h1 + "," + h2 + "&label=Assembly%202026"
	if got := ServerLink(s); got != want {
		t.Errorf("ServerLink:\n got  %s\n want %s", got, want)
	}
	s.LanAddr = netip.MustParseAddr("fd12:3456::1")
	s.Hashes = [2]string{h1, ""}
	s.DisplayName = ""
	want = "gawk://server?relay=https%3A%2F%2F%5Bfd12%3A3456%3A%3A1%5D%3A4433&certHash=" + h1
	if got := ServerLink(s); got != want {
		t.Errorf("ServerLink v6:\n got  %s\n want %s", got, want)
	}
	s.LanAddr = netip.Addr{}
	if got := ServerLink(s); got != "" {
		t.Errorf("no LAN address: %q, want empty", got)
	}
}

// docs/76 §6.1 item 6: the host's own /app/config.js names the relay by
// LAN address with both hashes and turns the publish-secret prompt off.
func TestConfigJSGolden(t *testing.T) {
	got := string(ConfigJS(lanState(HeaderStandalone)))
	want := "// Generated by gawk-relay for this machine's /app/ (docs/76 §6.1 item 6).\n" +
		`window.__GAWK_CONFIG__ = {"relayUrl":"https://192.168.1.20:4433","relayCertHashes":["` + h1 + `","` + h2 + `"],"requirePublishSecret":false};` + "\n"
	if got != want {
		t.Errorf("config.js:\n got  %s\n want %s", got, want)
	}

	// No LAN address: the host's own machine still reaches the relay on
	// loopback. No hashes (an explicit -cert-file): an empty list, never null.
	s := lanState(HeaderStandalone)
	s.LanAddr = netip.Addr{}
	s.Hashes = [2]string{}
	got = string(ConfigJS(s))
	if !strings.Contains(got, `{"relayUrl":"https://127.0.0.1:4433","relayCertHashes":[],"requirePublishSecret":false}`) {
		t.Errorf("config.js without LAN or hashes:\n%s", got)
	}
}
